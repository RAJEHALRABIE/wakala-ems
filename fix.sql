في تطبيق Wakala-ems قمنا باضافة حقول وتعديل تسميات :

اولا اعرف استوعب هذا النص"إضافة الـ 20% في نزع الملكية (خاصة في السعودية) هي تعويض إضافي يُمنح للمالك فوق القيمة السوقية للعقار، سواء عند نزعها كلياً أو وضع اليد عليها مؤقتًا، وذلك لحماية حقوق المالك عن إجراءات النزع وأي أضرار ناتجة عنها، مع ضمان الحصول على تعويض عادل عن أجرة المثل للعقار في حال وضع اليد المؤقت، ويُضاف إليها الـ 20% أيضاً. 
تفاصيل التعويض:
نزع الملكية الكلي: القيمة السوقية للعقار + 20% من قيمته السوقية (كعوض إضافي) + تعويض عن الأضرار الناتجة عن الإجراءات.
وضع اليد المؤقت: أجرة المثل للعقار (كحد أدنى) + 20% فوق أجرة المثل (كعوض عن الوضع المؤقت) + تعويض الأضرار الناجمة عن وضع اليد. 
لماذا هذه الإضافة (20%):
تعويض إضافي: هي نسبة مئوية تُضاف كتعويض عن "النزع" أو "الوضع المؤقت" بحد ذاته، وليس عن قيمة العقار فقط.
حماية المالك: النظام يهدف لضمان تعويض عادل وشامل للمالكين المتضررين من إجراءات نزع الملكية للمنفعة العامة.
تنظيم واضح: النظام السعودي الجديد يضع آليات محددة لتقييم العقارات والشفافية في صرف التعويضات وحقوق المالكين، بما في ذلك الإعفاء من ضريبة التصرفات العقارية عند شراء بديل في بعض الحالات."

هناك حقل في (تبويب) "المعلومات المالية" بملف العميل بمسمى (نسبة وضع اليد) هذا الحقل ياخذ رقم (قيمه) وهي تمثل نسبة من 100% (بمعنى عندما تكون القيمة المدخلة هي 15 فانها تعامل كنسبة % بمعنى 15%.
هذه القيمة هي نسبة تعويض مضاف لقيمة تعويض النزع المقدرة.
فمثلا هناك تقدير تعويض بقيمة 100 ريال لسعر المتر ومساحة الارض 100م فان التعويض هو حاصل مجموع ضرب (المساحة الاجمالية×السعر المقدر للمتر)+(اجمالي التعويض×15%) في حال النزع كان كلي فانه ياخذ اجمالي المساحه المسجلة بمستند العقار (صك,احكام,...).
وفي حال النزع الجزئي تكون المعادلة كالتالي:
(المساحة المنزوعه×السعر المقدر للمتر)+(اجمالي التعويض×15%)
احيانا يكون النزع عباره عن احياءات فقط فان السعر تقديري. للاحياءات فقط لان الارض حكومية ,الاحياءات مثل (ابار,منازل,احواش,اسوار,اشجار,حضائر اغنام,اخرى).

