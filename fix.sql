منطق إظهار الحقول حسب نوع النزع
ما تصفه يبدو صحيحًا من ناحية تجربة الاستخدام والمنطق:

وجود حقل expropriationType مع إظهار حقول إضافية عند اختيار:

نزع كلي: استخدام مساحة الصك كاملة في الحساب، وعدم إظهار حقول “المساحة المنزوعة / المتبقية”.

نزع جزئي: إظهار حقول:

رقم قرار النزع الجزئي.

expropriated_area (المساحة المنزوعة).

remaining_area (المساحة المتبقية).

مرفقات الرفع المساحي/الخرائط إن وُجدت.

هذا يتوافق مع ما تحتاجه في المعادلات لاحقًا: استخدام expropriated_area في الحساب بدلاً من مساحة الصك عند النزع الجزئي، مع بقاء remaining_area للمعلومة فقط.

حقل improvement_type
تركه كنص حر (Text input) خطوة مقبولة كبداية، لكن على المدى المتوسط يفضَّل بشدة تحويله إلى قائمة منسدلة لضبط البيانات:

القيم المقترحة:

RESIDENTIAL_BUILDING – منزل/سكن.

ANIMAL_SHELTER – حظيرة أغنام أو ماشية.

FRUIT_TREES – أشجار مثمرة.

FENCE – سور.

OTHER – أخرى (مع حقل نصي يظهر فقط عند اختيارها لكتابة الوصف).

ميزة القائمة المنسدلة:

تسهّل الإحصائيات والتقارير لاحقًا حسب نوع الإحياء.

تقلل الأخطاء الإملائية واختلاف الصياغة بين الموظفين.

إن رغبت في تحويله الآن لقائمة، المنطق في الواجهة يكون كالتالي:

حقل نوع الإحياء (قائمة منسدلة بالأنواع أعلاه).

إذا كانت القيمة OTHER، أظهر حقل نص إضافي مثل: وصف الإحياء الآخر.

نقاط سريعة للتأكد من صحة الكود
حتى بدون رؤية الشيفرة، تأكد من الآتي:

ربط الحقول الجديدة (expropriated_area, remaining_area, improvement_type) بنفس أسماء الأعمدة في الـ schema حتى لا تظهر أخطاء Typescript أو runtime.

عند حفظ النموذج:

تحويل قيم المساحة إلى أرقام (مثل Number(value) أو parseFloat) قبل إرسالها للـ API.

في حالة النزع الكلي، تجاهل قيمة expropriated_area في الحساب، وفي النزع الجزئي استخدمها في المعادلة.

في الواجهة، تأكد أن القيمة الافتراضية لـ expropriationType هي FULL، حتى لا تظهر حقول النزع الجزئي بشكل مربك من البداية.

يمكن جعل حقل الإحياءات يدعم أكثر من نوع في نفس العقار باستخدام مجموعة من مربعات الاختيار (Checkboxes) بدل قائمة منسدلة واحدة، وهذا مناسب جدًا لحالتك.

تصميم الحقل في الواجهة
أنشئ مجموعة بعنوان مثل: نوع الإحياءات الموجودة في العقار.

داخلها عدة Checkboxes، مثلاً:

منزل/سكن (RESIDENTIAL_BUILDING)

حظيرة أغنام أو ماشية (ANIMAL_SHELTER)

أشجار مثمرة (FRUIT_TREES)

سور (FENCE)

أخرى (OTHER)

عندما يحدد المستخدم خيار أخرى (OTHER):

يظهر حقل نص إضافي: وصف الإحياءات الأخرى ليكتب فيه تفاصيل مثل: مستودع، بئر، مظلات، إلخ.

بهذا الشكل يمكن اختيار أكثر من نوع معًا (مثلاً منزل + سور + أشجار)، ثم تستخدم في قاعدة البيانات إما:

حقل improvement_types من نوع JSON / نص يخزن مصفوفة القيم مثل:

["RESIDENTIAL_BUILDING","FRUIT_TREES"]

أو جدول فرعي لاحقًا لو أردت تفصيلاً أكبر لكل نوع وقيمته.

هذا التصميم يعطيك:

مرونة لاختيار عدة أنواع في نفس الملف.

بيانات منظمة يسهل تحليلها لاحقًا (عدد الملفات التي فيها أشجار مثمرة، مثلاً).

